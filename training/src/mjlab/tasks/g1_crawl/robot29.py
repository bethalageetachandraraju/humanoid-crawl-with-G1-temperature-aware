# MuJoCo joint order with wrist pitch/yaw braced out: legs (12), waist (3),
# arms (10).
CRAWL_JOINTS_29 = (
  "left_hip_pitch_joint",
  "left_hip_roll_joint",
  "left_hip_yaw_joint",
  "left_knee_joint",
  "left_ankle_pitch_joint",
  "left_ankle_roll_joint",
  "right_hip_pitch_joint",
  "right_hip_roll_joint",
  "right_hip_yaw_joint",
  "right_knee_joint",
  "right_ankle_pitch_joint",
  "right_ankle_roll_joint",
  "waist_yaw_joint",
  "waist_roll_joint",
  "waist_pitch_joint",
  "left_shoulder_pitch_joint",
  "left_shoulder_roll_joint",
  "left_shoulder_yaw_joint",
  "left_elbow_joint",
  "left_wrist_roll_joint",
  "right_shoulder_pitch_joint",
  "right_shoulder_roll_joint",
  "right_shoulder_yaw_joint",
  "right_elbow_joint",
  "right_wrist_roll_joint",
)
BRACED_JOINTS = tuple(
  f"{side}_wrist_{axis}_joint"
  for side in ("left", "right")
  for axis in ("pitch", "yaw")
)

# Load on each braced joint. The joints are welded in the model, but the moment
# that crosses them -- what the motor and the brace carry together about the
# joint axis -- is still there: a MuJoCo torque sensor at a site on the joint's
# child body, at the joint origin and in the body frame, measures the full
# interaction torque between that body and its parent, and its component along
# the joint axis is the joint load. Joint name -> (site name, axis in that frame).
BRACED_LOADS_29: dict[str, tuple[str, tuple[float, float, float]]] = {
  f"{side}_wrist_{axis}_joint": (f"{side}_wrist_{axis}_load", vec)
  for side in ("left", "right")
  for axis, vec in (("pitch", (0.0, 1.0, 0.0)), ("yaw", (0.0, 0.0, 1.0)))
}
# Rating of the braced 4010 motors. Keeping the braced moment under it means the
# wrist is safe even if the brace flexes and the motor ends up taking the load.
BRACED_TORQUE_LIMIT = 5.0

FEET_29 = ("left_ankle_roll_link", "right_ankle_roll_link")
# The printed extension is the "hand": it carries the domed contact tip.
HANDS_29 = ("left_forearm_extension", "right_forearm_extension")
LEFT_LIMBS_29 = ("left_ankle_roll_link", "left_forearm_extension")
RIGHT_LIMBS_29 = ("right_ankle_roll_link", "right_forearm_extension")

# Regex matching both the feet and the hands, for the crawl contact sensor.
CONTACT_BODIES_29 = r".*_(ankle_roll_link|forearm_extension)$"

# Sites the clearance rewards cast rays from; the hand sites sit on the dome tip.
HAND_SITES_29 = ("left_hand_contact", "right_hand_contact")
LIMB_SITES_29 = ("left_foot", "right_foot") + HAND_SITES_29


def _load_pose() -> tuple[dict[str, float], float]:
  """Generated crawl pose, or a placeholder that ``get_crawl_spec_29`` rejects."""
  if not CRAWL_POSE_29.exists():
    assert CRAWL_INIT_STATE.joint_pos is not None
    placeholder = {**CRAWL_INIT_STATE.joint_pos, "waist_(roll|pitch)_joint": 0.0}
    return placeholder, math.nan
  data = json.loads(CRAWL_POSE_29.read_text())
  return data["joint_pos"], float(data["extension_length"])


_POSE_JOINT_POS, _POSE_EXTENSION_LENGTH = _load_pose()


def get_crawl_spec_29(check_pose: bool = True) -> mujoco.MjSpec:
  """Stock 29-DoF G1 with hands removed, wrists braced and extensions added."""
  if check_pose and not math.isclose(
    _POSE_EXTENSION_LENGTH, EXTENSION_LENGTH, abs_tol=1e-9
  ):
    raise RuntimeError(
      f"The crawl pose in {CRAWL_POSE_29.name} is missing or was solved for a "
      f"{_POSE_EXTENSION_LENGTH * 1000:.1f} mm extension, but EXTENSION_LENGTH is "
      f"{EXTENSION_LENGTH * 1000:.1f} mm. Run:\n"
      "  uv run python scripts/retarget_crawl_animation.py"
    )
  spec = mujoco.MjSpec.from_file(str(G1_XML))

  # Rubber hands (visual mesh + collision capsule), and the wrist capsule that
  # the brace now encloses.
  removed_geoms = {
    f"{side}_{part}_collision"
    for side in ("left", "right")
    for part in ("hand", "wrist")
  }
  for geom in list(spec.geoms):
    if geom.meshname.endswith("_rubber_hand") or geom.name in removed_geoms:
      spec.delete(geom)
  for mesh in list(spec.meshes):
    if mesh.name.endswith("_rubber_hand"):
      spec.delete(mesh)
  # Braced joints: deleting a joint welds its body to the parent at angle zero.
  # A site at the joint origin keeps the joint measurable (``BRACED_LOADS_29``).
  for name, (site, axis) in BRACED_LOADS_29.items():
    joint = spec.joint(name)
    assert tuple(joint.axis) == axis, (name, tuple(joint.axis))
    joint.parent.add_site(name=site, pos=joint.pos.tolist(), size=[0.006, 0, 0])
    spec.delete(joint)

  for side in ("left", "right"):
    # Wrist-yaw link without the hand's mass.
    link = spec.body(f"{side}_wrist_yaw_link")
    inertial = _WRIST_YAW_MOTOR_INERTIAL[side]
    link.explicitinertial = True
    link.mass = inertial.mass
    link.ipos[:] = inertial.ipos
    link.iquat[:] = inertial.iquat
    link.inertia[:] = inertial.inertia

    # Brace: a welded body on the wrist roll link, so it turns with wrist roll.
    brace = spec.body(f"{side}_wrist_roll_link").add_body(name=f"{side}_wrist_brace")
    span = [BRACE_START, 0.0, 0.0, BRACE_END, 0.0, 0.0]
    brace.add_geom(
      name=f"{side}_wrist_brace_collision",
      type=mujoco.mjtGeom.mjGEOM_CYLINDER,
      fromto=span,
      size=[BRACE_RADIUS, 0, 0],
      mass=BRACE_MASS,
      typeinertia=mujoco.mjtGeomInertia.mjINERTIA_SHELL,  # A sleeve, not a rod.
      group=3,
      rgba=[0.2, 0.6, 0.2, 0.3],
    )
    brace.add_geom(
      type=mujoco.mjtGeom.mjGEOM_CYLINDER,
      fromto=span,
      size=[BRACE_RADIUS, 0, 0],
      density=0,
      contype=0,
      conaffinity=0,
      group=2,
      rgba=_BRACE_RGBA,
    )

    # Extension: a welded body on the wrist-yaw flange. Collision is a capsule
    # whose far cap is the dome; it starts one radius in from the flange so its
    # near cap stays inside the part.
    ext = link.add_body(name=f"{side}_forearm_extension", pos=[FLANGE_X, 0, 0])
    r, length = EXTENSION_RADIUS, EXTENSION_LENGTH
    ext.add_geom(
      name=f"{side}_forearm_tip_collision",
      type=mujoco.mjtGeom.mjGEOM_CAPSULE,
      fromto=[r, 0, 0, length - r, 0, 0],
      size=[r, 0, 0],
      mass=EXTENSION_MASS,
      group=3,
      rgba=[0.2, 0.6, 0.2, 0.3],
    )
    # Visual: flat-backed tube plus the dome.
    for geom in (
      ext.add_geom(
        type=mujoco.mjtGeom.mjGEOM_CYLINDER, fromto=[0, 0, 0, length - r, 0, 0]
      ),
      ext.add_geom(type=mujoco.mjtGeom.mjGEOM_SPHERE, pos=[length - r, 0, 0]),
    ):
      geom.size[0] = r
      geom.density = 0
      geom.contype = geom.conaffinity = 0
      geom.group = 2
      geom.rgba[:] = _PRINT_RGBA
    ext.add_site(name=f"{side}_hand_contact", pos=[length, 0, 0], size=[0.008, 0, 0])

    # The brace overlaps the elbow link's capsule and butts against the
    # extension; neither is a real contact.
    spec.add_exclude(bodyname1=f"{side}_wrist_brace", bodyname2=f"{side}_elbow_link")
    spec.add_exclude(
      bodyname1=f"{side}_wrist_brace", bodyname2=f"{side}_forearm_extension"
    )
  return spec


# Crawl pose: legs, ankles and waist yaw from the source ``G1_CFG.init_state``,
# waist roll/pitch zero, arms solved for the extension tip by
# ``scripts/retarget_crawl_animation.py`` (stored in ``CRAWL_POSE_29``).
CRAWL_INIT_STATE_29 = EntityCfg.InitialStateCfg(
  pos=(0.0, 0.0, 0.22),
  rot=(0.721249, -0.000001, 0.692676, -0.000012),  # ~1.53 rad pitch: base +X down.
  joint_pos=dict(_POSE_JOINT_POS),
  joint_vel={".*": 0.0},
)

# Robot-terrain contacts only, every contact frictional, robot friction wins over
# the terrain's: the same policy ``robot.py`` uses.
CRAWL_COLLISION_29 = CollisionCfg(
  geom_names_expr=(r".*_collision.*",),
  contype=0,
  conaffinity=1,
  condim=3,
  priority=1,
  friction=(0.6,),
)

# As above but with self-collision on, frictionless between the robot's own
# geoms (as in the asset zoo's ``FULL_COLLISION``). Stops the policy from
# exploring gaits that pass an arm through a leg.
_LIMB_GEOMS = r"^(left|right)_(foot[1-7]|forearm_tip)_collision$"
CRAWL_SELF_COLLISION_29 = CollisionCfg(
  geom_names_expr=(r".*_collision.*",),
  contype=1,
  conaffinity=1,
  condim={_LIMB_GEOMS: 3, ".*_collision.*": 1},
  priority={_LIMB_GEOMS: 1, ".*": 0},
  friction={_LIMB_GEOMS: (0.6,)},
)

# As above, with torsional friction on the limbs (condim 4): a planted foot or
# tip resists twisting about the contact normal, as a rubber sole does on
# carpet. With condim 3 a foot can spin in place for free, and a stand-to-crawl
# learned that way caught its toe in the carpet on the robot (2026-10-29). The
# torsional coefficient (m) is randomized per episode by ``floor_friction``.
CRAWL_SELF_COLLISION_29_TORSION = CollisionCfg(
  geom_names_expr=(r".*_collision.*",),
  contype=1,
  conaffinity=1,
  condim={_LIMB_GEOMS: 4, ".*_collision.*": 1},
  priority={_LIMB_GEOMS: 1, ".*": 0},
  friction={_LIMB_GEOMS: (0.6, 0.02, 0.0001)},
)

# Motor command delay, in 5 ms physics steps. The buffer holds up to
# ``ACTION_DELAY_MAX_STEPS`` (20 ms); a lag is drawn per robot and held for
# ``ACTION_DELAY_HOLD_STEPS`` (1 s), like a real control loop whose latency
# drifts rather than jumps. The robustness curriculum narrows the range to 0 at
# its first level and widens it as the gait matures; without the curriculum
# (play, the torque monitor) the full 0-20 ms range applies.
ACTION_DELAY_MAX_STEPS = 4
ACTION_DELAY_HOLD_STEPS = 200

# Motor groups for the 25 active joints: arms incl. wrist roll 5020 (25 Nm), hip
# pitch/yaw and waist yaw 7520-14 (88 Nm), hip roll and knee 7520-22 (139 Nm),
# ankles and waist roll/pitch 2 x 5020 (50 Nm). No 4010s: the braced wrist
# pitch/yaw motors are not in the model.
CRAWL_ARTICULATION_29 = EntityArticulationInfoCfg(
  actuators=tuple(
    replace(
      actuator,
      delay_min_lag=0,
      delay_max_lag=ACTION_DELAY_MAX_STEPS,
      delay_update_period=ACTION_DELAY_HOLD_STEPS,
    )
    for actuator in (
      G1_ACTUATOR_5020,
      G1_ACTUATOR_7520_14,
      G1_ACTUATOR_7520_22,
      G1_ACTUATOR_WAIST,
      G1_ACTUATOR_ANKLE,
    )
  ),
  soft_joint_pos_limit_factor=0.9,
)


def _motor_table() -> dict[str, tuple[float, float, float]]:
  """Joint name -> (kp, kd, peak torque) for every actuated joint."""
  table: dict[str, tuple[float, float, float]] = {}
  for actuator in CRAWL_ARTICULATION_29.actuators:
    assert isinstance(actuator, BuiltinPositionActuatorCfg)
    assert actuator.effort_limit is not None
    for name in CRAWL_JOINTS_29:
      if any(re.fullmatch(expr, name) for expr in actuator.target_names_expr):
        table[name] = (actuator.stiffness, actuator.damping, actuator.effort_limit)
  assert set(table) == set(CRAWL_JOINTS_29), set(CRAWL_JOINTS_29) - set(table)
  return {name: table[name] for name in CRAWL_JOINTS_29}  # Policy joint order.


# PD gains and peak torque per joint, for torque-safety rewards and metrics.
MOTORS_29 = _motor_table()


def deploy_target_clip() -> dict[str, tuple[float, float]]:
  """Joint name -> (lower, upper) range, for an action term's ``clip``.

  The robot controller clamps every PD target to the joint's range before
  sending it (the deploy bundle's ``joint_limits``, exported from this model).
  Training with the same clamp keeps the policy from relying on targets past a
  limit as extra torque, which the robot will not give it.
  """
  spec = get_crawl_spec_29()
  ranges = {j.name: (float(j.range[0]), float(j.range[1])) for j in spec.joints}
  return {re.escape(name): ranges[name] for name in CRAWL_JOINTS_29}


def get_g1_crawl_robot_cfg_29(self_collision: bool = True) -> EntityCfg:
  """Fresh config for the modified 29-DoF crawl G1 (new instance each call)."""
  return EntityCfg(
    init_state=CRAWL_INIT_STATE_29,
    collisions=(CRAWL_SELF_COLLISION_29 if self_collision else CRAWL_COLLISION_29,),
    spec_fn=get_crawl_spec_29,
    articulation=CRAWL_ARTICULATION_29,
  )
