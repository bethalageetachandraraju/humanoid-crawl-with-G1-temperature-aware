# Wrist brace: a cylinder sleeve in the ``*_wrist_roll_link`` frame, whose +X is
# the forearm axis and whose origin is the wrist roll joint. The wrist motors
# reach 34.1 mm from the axis (pitch motor), so 40 mm outer leaves ~2 mm
# clearance plus a 4 mm wall. It starts 10 mm past the roll joint so roll can
# still turn, and ends at the wrist-yaw flange (38 + 46 + 41.5 mm).
BRACE_START = 0.010
BRACE_END = 0.1255
BRACE_RADIUS = 0.040
BRACE_MASS = 0.15  # ~110 cm^3 of solid wall in PLA/PETG plus clamps; weigh it.

# Forearm extension: bolted to the wrist-yaw flange, which is 41.5 mm past the
# wrist-yaw axis and about 48 mm across. Cylinder of radius EXTENSION_RADIUS
# ending in a hemisphere of the same radius; EXTENSION_LENGTH is flange to tip.
FLANGE_X = 0.0415  # In ``*_wrist_yaw_link``.
EXTENSION_LENGTH = 0.100
EXTENSION_RADIUS = 0.025
EXTENSION_MASS = 0.10  # ~180 cm^3 envelope at ~45% effective fill; weigh it.

_PRINT_RGBA = (0.95, 0.55, 0.15, 1.0)  # Orange, so printed parts stand out.
_BRACE_RGBA = (0.95, 0.55, 0.15, 0.45)  # Translucent: the motors show through.


# The stock ``*_wrist_yaw_link`` inertial (0.2546 kg, centre of mass 70.8 mm out,
# past the 41.5 mm flange) includes the rubber hand. Splitting it by the two
# meshes' volume centroids (motor 20.6 mm, hand 106.1 mm) gives hand 149.4 g and
# motor 105.1 g; the motor's inertia is its mesh's at that density.
class _Inertial(NamedTuple):
  mass: float
  ipos: tuple[float, float, float]
  iquat: tuple[float, float, float, float]
  inertia: tuple[float, float, float]


_WRIST_YAW_MOTOR_INERTIAL = {
  "left": _Inertial(
    mass=0.1051,
    ipos=(0.02064, 0.0009, 0.0),
    iquat=(0.6698, -0.0137, -0.01386, 0.74228),
    inertia=(5.5163e-05, 4.5183e-05, 3.3474e-05),
  ),
  "right": _Inertial(
    mass=0.1051,
    ipos=(0.02064, -0.0009, 0.0),
    iquat=(0.74226, -0.01395, -0.01379, 0.66983),
    inertia=(5.5166e-05, 4.5182e-05, 3.3477e-05),
  ),
}

