"""The 29-DoF Unitree G1, modified for crawling, configured for the crawl task.

This is the robot on the bench, with three hardware changes per arm:

* **Rubber hand removed.** Its visual mesh, its collision capsule and its mass
  (149 g, split out of the ``*_wrist_yaw_link`` inertial; see
  ``_WRIST_YAW_MOTOR_INERTIAL``) are gone.
* **3D-printed wrist brace.** A rigid sleeve clamped from just past the wrist
  roll joint to the wrist-yaw motor's output flange. It locks wrist pitch and
  yaw at zero, so in the model those two joints are deleted and the links are
  welded; wrist roll stays free and actuated. On hardware, hold the four braced
  motors at zero with low gains (or put them in damping mode) -- the brace, not
  the 5 Nm motors, carries the load.
* **3D-printed forearm extension.** A cylinder bolted to the wrist-yaw flange,
  ending in a hemispherical dome that is the new contact point with the ground.

With these the arm is kinematically the source project's "simple forearm"
(shoulder pitch/roll/yaw, elbow, wrist roll, then one rigid link ending in a
round tip): elbow axis to tip is 225.5 mm (flange) + ``EXTENSION_LENGTH``,
against 300 mm on the 23-DoF robot of ``robot.py``. The robot keeps its waist
roll and pitch, so the policy controls 25 joints.

The crawl pose and the reset animation depend on where the tip is, so both are
generated by ``scripts/retarget_crawl_animation.py`` (it re-solves the arm so the
tip and forearm axis land where the source robot's ball hand did). After
changing ``EXTENSION_LENGTH``, run it again; building the robot refuses to use a
pose solved for a different length.

Everything else carries over: legs, feet and all shared joint limits are
identical to the source robot.
"""

